/**
 * Autoload this plugin's own classes.
 * By hand, because a composer install has no plugin-local vendor/ and the release zip has no root autoloader.
 */
spl_autoload_register(static function (string $class): void {
    $namespace = 'RAH\\SEO\\';
    if (!str_starts_with($class, $namespace)) {
        return;
    }

    $relative = substr($class, strlen($namespace));

    /** Prefixed dependencies share the namespace, but Strauss autoloads them */
    if (str_starts_with($relative, 'Vendor\\')) {
        return;
    }

    $file = __DIR__ . '/lib/rah/' . str_replace('\\', '/', $relative) . '.php';

    if (is_readable($file)) {
        require_once $file;
    }
});

/** Dependencies, generated by Strauss and committed */
require_once __DIR__ . '/vendor-prefixed/autoload.php';

define('RHSEO_PATH', plugin_dir_path(__FILE__));
define('RHSEO_BASENAME', plugin_basename(__FILE__));
define('RHSEO_UPGRADE_VERSION', '1.3.9'); // Highest version with an upgrade routine.

RAH\SEO\UpdateChecker::init(__FILE__);

/**
 * Initialize the $seo instance
 *
 * @return \RAH\SEO\SEO
 */
function rhseo()
{
    static $instance;
    if (!isset($instance)) {
        $instance = new RAH\SEO\SEO();
    }
    return $instance;
}
rhseo();
